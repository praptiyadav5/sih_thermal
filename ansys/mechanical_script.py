"""
PyMechanical Full Script Assembler & Solver Bridge
Assembles full ANSYS PyMechanical thermal simulation scripts and manages solver execution.
"""
import os
from .materials import generate_composite_ansys_materials
from .geometry import generate_ansys_geometry_apdl
from .boundary_conditions import generate_ansys_boundary_conditions_apdl

class PyMechanicalScriptBuilder:
    """
    Builds complete PyMechanical Python scripts for thermal FEA analysis.
    """
    def __init__(self, shelter_config, weather_data, wall_stack, roof_stack, floor_stack):
        self.config = shelter_config
        self.weather = weather_data
        self.wall_stack = wall_stack
        self.roof_stack = roof_stack
        self.floor_stack = floor_stack

    def build_pymechanical_python_script(self):
        """
        Generates standalone runnable PyMechanical Python script.
        """
        l = self.config.get('length', 6.0)
        w = self.config.get('width', 4.0)
        h = self.config.get('height', 2.4)
        shape = self.config.get('shape', 'Rectangular')
        win_area = self.config.get('window_area', 1.5)
        door_area = self.config.get('door_area', 2.0)
        orient = self.config.get('orientation_deg', 0.0)

        mean_temp = float(self.weather['temperature_c'].mean())
        mean_solar = float(self.weather['solar_radiation_w_m2'].mean())
        mean_wind = float(self.weather['wind_speed_m_s'].mean())

        apdl_mats = generate_composite_ansys_materials(self.wall_stack, start_mat_id=1)
        apdl_geom = generate_ansys_geometry_apdl(l, w, h, shape, roof_height=0.8, window_area=win_area, door_area=door_area, orientation_deg=orient)
        apdl_bc = generate_ansys_boundary_conditions_apdl(mean_temp, mean_solar, mean_wind)

        python_script = f"""# =========================================================
# PyMechanical Transient Thermal Simulation Script
# Auto-generated by Thermal Shelter Simulation Platform
# Location: Ladakh Region | Geometry: {shape} ({l}m x {w}m x {h}m)
# =========================================================

import os
try:
    from ansys.mapdl.core import launch_mapdl
    print("Launching ANSYS MAPDL Solver...")
    mapdl = launch_mapdl(loglevel="WARNING")
    mapdl.clear()
    mapdl.prep7()
    
    # Material Definitions
    apdl_mats = '''
{apdl_mats}
'''
    mapdl.input_strings(apdl_mats)
    
    # Geometry Definitions
    apdl_geom = '''
{apdl_geom}
'''
    mapdl.input_strings(apdl_geom)
    
    # Boundary Conditions & Thermal Loads
    apdl_bc = '''
{apdl_bc}
'''
    mapdl.input_strings(apdl_bc)
    
    # Solution Settings & Execution
    mapdl.slashsolu()
    mapdl.antype("STATIC")  # Steady state or Transient thermal
    mapdl.solve()
    mapdl.finish()
    
    # Post-Processing
    mapdl.post1()
    mapdl.set(1, 1)
    t_min = mapdl.get_value("NODE", 0, "MN", "TEMP")
    t_max = mapdl.get_value("NODE", 0, "MX", "TEMP")
    print(f"ANSYS Mechanical thermal analysis completed. T_min={{t_min:.2f}}C, T_max={{t_max:.2f}}C")
    
    mapdl.exit()
    
except ImportError:
    print("PyAnsys / PyMAPDL library not installed on local host. Skipping live ANSYS execution.")
except Exception as e:
    print(f"ANSYS Mechanical Execution error: {{e}}")
"""
        return python_script

    def check_ansys_availability(self):
        """
        Checks if PyMechanical or PyMAPDL is installed and accessible on host.
        """
        try:
            import ansys.mapdl.core as mapdl_core
            return True, "PyAnsys / PyMAPDL detected on host system."
        except ImportError:
            try:
                import ansys.mechanical.core as mech_core
                return True, "PyMechanical core detected on host system."
            except ImportError:
                return False, "PyMechanical / ANSYS not detected. Operating in High-Fidelity Physics Fallback Solver mode."
