
import streamlit as st


APP_KNOWLEDGE = {
    "Home": "Project overview and starting point.",
    "Shelter Design": "Configure the shelter design using the available controls.",
    "Climate Conditions": "Review environmental and climate inputs.",
    "Simulation": "Run the available shelter simulation.",
    "Results": "Inspect simulation outputs and performance.",
    "Comparison": "Compare available shelter designs or results.",
    "Optimization": "Explore possible design improvements.",
}


def get_local_answer(question):
    q = question.lower().strip()

    if any(x in q for x in ["hello", "hi", "hey", "good morning"]):
        return (
            "Hello! 👋 Welcome to Thermal Shelter Studio.\n\n"
            "I can guide you through shelter design, climate conditions, "
            "simulation, results, comparison, and optimization.\n\n"
            "What would you like to explore?"
        )

    if any(x in q for x in ["help", "what can you do", "features", "start"]):
        return (
            "## Welcome to Thermal Shelter Studio 🏔️\n\n"
            + "\n".join(
                f"- **{name}:** {description}"
                for name, description in APP_KNOWLEDGE.items()
            )
            + "\n\n**Suggested workflow:**\n"
            "1. Configure your shelter design.\n"
            "2. Review climate conditions.\n"
            "3. Run a simulation.\n"
            "4. Inspect results.\n"
            "5. Compare and optimize your design."
        )

    if any(x in q for x in ["shelter", "design", "insulation", "roof"]):
        return (
            "**Shelter Design 🏠**\n\n"
            "1. Open the Shelter Design page.\n"
            "2. Review the available design controls.\n"
            "3. Configure the shelter parameters.\n"
            "4. Review climate conditions before simulation.\n\n"
            "The best design depends on your climate, materials, "
            "geometry, and simulation objectives."
        )

    if any(x in q for x in ["climate", "weather", "temperature", "solar"]):
        return (
            "**Climate Conditions 🌤️**\n\n"
            "Open the Climate Conditions page and review the available "
            "environmental inputs, such as temperature and solar conditions "
            "if supported by your current configuration.\n\n"
            "Check these inputs before running a simulation."
        )

    if any(x in q for x in ["simulation", "simulate", "run model"]):
        return (
            "**Simulation ⚡**\n\n"
            "1. Configure your shelter.\n"
            "2. Review the climate inputs.\n"
            "3. Open the Simulation page.\n"
            "4. Follow the available simulation controls.\n"
            "5. Open Results after the simulation finishes.\n\n"
            "If the simulation fails, share the error message so I can "
            "help troubleshoot it."
        )

    if any(x in q for x in ["result", "performance", "heat loss", "efficiency"]):
        return (
            "**Understanding Results 📊**\n\n"
            "Open the Results page and inspect the values and charts "
            "generated by your simulation.\n\n"
            "I can help interpret the actual outputs if you provide "
            "their values or a screenshot. I won't invent simulation results."
        )

    if any(x in q for x in ["compare", "comparison", "difference"]):
        return (
            "**Design Comparison ⚖️**\n\n"
            "Open Comparison to review the alternatives supported by your app. "
            "Where possible, compare designs using consistent climate inputs "
            "and simulation settings."
        )

    if any(x in q for x in ["optim", "improve", "best design"]):
        return (
            "**Optimization 🚀**\n\n"
            "Open Optimization and review the objective, constraints, "
            "and available settings. Evaluate the resulting design against "
            "your thermal performance goals before selecting it."
        )

    return (
        "I can help you navigate Thermal Shelter Studio and understand "
        "its workflow.\n\n"
        "Try asking:\n"
        "- How do I design a shelter?\n"
        "- How do I run a simulation?\n"
        "- How do I understand the results?\n"
        "- How can I improve my design?\n\n"
        "For questions requiring actual simulation data, share the relevant "
        "values or screenshot so I can give a grounded explanation."
    )


def render_chatbot():
    # Shared session state keeps the chat available across page navigation.
    if "thermal_chat_open" not in st.session_state:
        st.session_state.thermal_chat_open = False

    if "thermal_chat_history" not in st.session_state:
        st.session_state.thermal_chat_history = [
            {
                "role": "assistant",
                "content": (
                    "Hi! 👋 I'm your Thermal AI Assistant.\n\n"
                    "I can help you design shelters, understand climate "
                    "conditions, and navigate simulations. What would "
                    "you like to do today?"
                ),
            }
        ]

    # Style the floating launcher and chat panel.
    st.markdown(
        """
        <style>
        .st-key-thermal_chat_launcher {
            position: fixed;
            right: 24px;
            bottom: 22px;
            width: 190px;
            z-index: 99999;
            background: #102033;
            border: 1px solid #2a526d;
            border-radius: 16px;
            padding: 8px;
            box-shadow: 0 8px 30px rgba(0,0,0,.4);
        }

        .st-key-thermal_chat_launcher button {
            width: 100%;
            border-radius: 12px;
            min-height: 48px;
            font-weight: 700;
        }

        .st-key-thermal_chat_panel {
            position: fixed;
            right: 24px;
            bottom: 86px;
            width: 370px;
            max-width: calc(100vw - 32px);
            max-height: 72vh;
            overflow-y: auto;
            z-index: 99998;
            background: #0c1422;
            border: 1px solid #29445e;
            border-radius: 18px;
            padding: 16px;
            box-shadow: 0 12px 45px rgba(0,0,0,.55);
        }

        .thermal-chat-title {
            font-size: 21px;
            font-weight: 750;
            color: #eaf4ff;
        }

        .thermal-chat-subtitle {
            color: #9db1c8;
            font-size: 12px;
            margin-top: 3px;
            margin-bottom: 12px;
        }

        @media (max-width: 600px) {
            .st-key-thermal_chat_panel {
                right: 10px;
                bottom: 76px;
                width: calc(100vw - 20px);
                max-width: none;
                max-height: 75vh;
            }

            .st-key-thermal_chat_launcher {
                right: 12px;
                bottom: 12px;
            }
        }
        </style>
        """,
        unsafe_allow_html=True,
    )

    # Closed state: show only the floating button.
    if not st.session_state.thermal_chat_open:
        with st.container(key="thermal_chat_launcher"):
            if st.button(
                "🤖  Chat with Thermal AI",
                key="thermal_open_chat",
                type="primary",
            ):
                st.session_state.thermal_chat_open = True
                st.rerun()

        return

    # Open state: show the floating chat panel.
    with st.container(key="thermal_chat_panel"):
        header_col, close_col = st.columns([5, 1])

        with header_col:
            st.markdown(
                '<div class="thermal-chat-title">'
                '🤖 Thermal AI Assistant</div>'
                '<div class="thermal-chat-subtitle">'
                'Your shelter design guide · Ready to help'
                '</div>',
                unsafe_allow_html=True,
            )

        with close_col:
            if st.button("✕", key="thermal_close_chat"):
                st.session_state.thermal_chat_open = False
                st.rerun()

        st.divider()

        # Suggested questions
        suggestions = [
            "What can you do?",
            "How do I design a shelter?",
            "How do I run a simulation?",
            "Explain my results",
        ]

        for i in range(0, len(suggestions), 2):
            cols = st.columns(2)

            for j, col in enumerate(cols):
                index = i + j
                if index >= len(suggestions):
                    continue

                with col:
                    if st.button(
                        suggestions[index],
                        key=f"thermal_suggestion_{index}",
                        use_container_width=True,
                    ):
                        st.session_state.thermal_pending_question = (
                            suggestions[index]
                        )
                        st.rerun()

        st.divider()

        # Show recent conversation.
        for message in st.session_state.thermal_chat_history[-12:]:
            with st.chat_message(message["role"]):
                st.markdown(message["content"])

        # Process a suggested question or submitted message.
        pending = st.session_state.pop(
            "thermal_pending_question", None
        )

        with st.form("thermal_chat_form", clear_on_submit=True):
            question = st.text_input(
                "Message",
                placeholder="Ask about your shelter...",
                label_visibility="collapsed",
            )
            submitted = st.form_submit_button(
                "Send ➤",
                use_container_width=True,
            )

        user_question = pending or (
            question.strip() if submitted else None
        )

        if user_question:
            st.session_state.thermal_chat_history.append(
                {"role": "user", "content": user_question}
            )

            answer = get_local_answer(user_question)

            st.session_state.thermal_chat_history.append(
                {"role": "assistant", "content": answer}
            )

            st.rerun()

        if st.button(
            "Clear conversation",
            key="thermal_clear_chat",
            use_container_width=True,
        ):
            st.session_state.thermal_chat_history = []
            st.rerun()
